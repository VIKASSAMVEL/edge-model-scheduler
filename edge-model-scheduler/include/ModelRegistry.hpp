#pragma once

#include <string>
#include <vector>
#include <unordered_map>
#include <fstream>
#include <sstream>
#include <iostream>

namespace edge_scheduler {

struct ModelConfig {
    std::string model_id;
    std::string engine_path;
    int priority_level;        // 1 = High, 2 = Medium, 3 = Low
    float latency_slo_ms;      // Maximum permissible latency deadline
    size_t input_buffer_bytes; // Buffer size for zero-copy memory allocation
    bool allow_quantization_fallback; // Whether INT8 fallback is allowed under heat
};

class ModelRegistry {
public:
    ModelRegistry() = default;

    bool register_model(const ModelConfig& config) {
        if (config.model_id.empty() || config.latency_slo_ms <= 0.0f) {
            return false;
        }
        models_[config.model_id] = config;
        return true;
    }

    const ModelConfig* get_model(const std::string& model_id) const {
        auto it = models_.find(model_id);
        if (it != models_.end()) {
            return &(it->second);
        }
        return nullptr;
    }

    bool has_model(const std::string& model_id) const {
        return models_.find(model_id) != models_.end();
    }

    size_t count() const {
        return models_.size();
    }

    std::vector<std::string> get_all_model_ids() const {
        std::vector<std::string> ids;
        ids.reserve(models_.size());
        for (const auto& pair : models_) {
            ids.push_back(pair.first);
        }
        return ids;
    }

    // Load simple configuration file format: model_id,engine_path,priority,slo_ms,buffer_bytes,fallback
    bool load_from_csv(const std::string& csv_path) {
        std::ifstream file(csv_path);
        if (!file.is_open()) {
            std::cerr << "[ModelRegistry] Failed to open config file: " << csv_path << std::endl;
            return false;
        }

        std::string line;
        // Skip header if present
        if (std::getline(file, line)) {
            if (line.find("model_id") == std::string::npos) {
                // Not a header line, process it
                parse_and_add_line(line);
            }
        }

        while (std::getline(file, line)) {
            if (!line.empty() && line[0] != '#') {
                parse_and_add_line(line);
            }
        }
        return true;
    }

    // Load deployment manifest generated by ModelCompiler (model_manifest.json)
    bool load_from_manifest(const std::string& manifest_path) {
        std::ifstream file(manifest_path);
        if (!file.is_open()) {
            std::cerr << "[ModelRegistry] Failed to open manifest: " << manifest_path << std::endl;
            return false;
        }

        std::string content((std::istreambuf_iterator<char>(file)),
                             std::istreambuf_iterator<char>());

        auto extract_str = [&](const std::string& key) -> std::string {
            size_t pos = content.find("\"" + key + "\":");
            if (pos == std::string::npos) return "";
            size_t start = content.find('"', pos + key.size() + 3);
            if (start == std::string::npos) return "";
            size_t end = content.find('"', start + 1);
            if (end == std::string::npos) return "";
            return content.substr(start + 1, end - start - 1);
        };

        auto extract_float = [&](const std::string& key, float default_val = 0.0f) -> float {
            size_t pos = content.find("\"" + key + "\":");
            if (pos == std::string::npos) return default_val;
            size_t start = content.find_first_of("0123456789.", pos + key.size() + 3);
            if (start == std::string::npos) return default_val;
            size_t end = content.find_first_of(",}\n", start);
            if (end == std::string::npos) return default_val;
            try {
                return std::stof(content.substr(start, end - start));
            } catch (...) {
                return default_val;
            }
        };

        std::string model_name = extract_str("model_name");
        std::string fp16_eng = extract_str("fp16_engine");
        float lat = extract_float("expected_fp16_latency_ms", 15.0f);

        if (model_name.empty()) {
            std::cerr << "[ModelRegistry] Invalid manifest: missing model_name\n";
            return false;
        }

        ModelConfig cfg;
        cfg.model_id = model_name;
        cfg.engine_path = fp16_eng.empty() ? (model_name + "_fp16.engine") : fp16_eng;
        cfg.priority_level = 1; // High priority perception
        cfg.latency_slo_ms = lat * 2.0f; // Target deadline: 2x nominal latency
        cfg.input_buffer_bytes = 3 * 640 * 640 * 2; // Default FP16 640x640 frame
        cfg.allow_quantization_fallback = true;

        register_model(cfg);
        std::cout << "[ModelRegistry] Loaded model '" << model_name << "' from manifest (SLO: " 
                  << cfg.latency_slo_ms << "ms, Engine: " << cfg.engine_path << ")\n";
        return true;
    }

private:
    void parse_and_add_line(const std::string& line) {
        std::stringstream ss(line);
        std::string item;
        std::vector<std::string> tokens;
        while (std::getline(ss, item, ',')) {
            tokens.push_back(item);
        }

        if (tokens.size() >= 6) {
            ModelConfig cfg;
            cfg.model_id = tokens[0];
            cfg.engine_path = tokens[1];
            cfg.priority_level = std::stoi(tokens[2]);
            cfg.latency_slo_ms = std::stof(tokens[3]);
            cfg.input_buffer_bytes = std::stoul(tokens[4]);
            cfg.allow_quantization_fallback = (tokens[5] == "1" || tokens[5] == "true");
            register_model(cfg);
        }
    }

    std::unordered_map<std::string, ModelConfig> models_;
};

} // namespace edge_scheduler
