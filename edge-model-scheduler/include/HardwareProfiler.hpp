namespace edge_scheduler {

/**
 * HardwareProfiler: Automated SoC Self-Calibration Engine
 *
 * On first boot or `edge-scheduler calibrate`, this profiler:
 *   1. Detects GPU compute capability, SM count, memory bandwidth
 *   2. Measures thermal dissipation rate under sustained load
 *   3. Determines optimal memory pool sizes based on available DRAM
 *   4. Calculates EWMA alpha and hysteresis thresholds for the specific SoC
 *   5. Emits a hardware_profile.yaml configuration file
 *
 * This eliminates manual per-platform tuning and makes the scheduler
 * portable across Jetson Nano, NX, Orin, and x86 development machines
 * without any code or config changes.
 */

struct GpuInfo {
    std::string device_name{"Unknown"};
    uint32_t sm_count{0};
    uint32_t cuda_cores{0};
    size_t total_memory_bytes{0};
    size_t free_memory_bytes{0};
    int compute_major{0};
    int compute_minor{0};
    int max_threads_per_sm{0};
    float peak_bandwidth_gbps{0.0f};
};

struct ThermalProfile {
    float idle_temp_c{0.0f};
    float sustained_temp_c{0.0f};
    float thermal_rise_rate_c_per_sec{0.0f};  // How fast temp rises under load
    float thermal_dissipation_rate_c_per_sec{0.0f}; // How fast temp drops after load
    float recommended_throttle_threshold_c{0.0f};
    float recommended_recovery_threshold_c{0.0f};
};

struct MemoryProfile {
    size_t total_system_ram_bytes{0};
    size_t available_ram_bytes{0};
    uint32_t recommended_pool_capacity{4};
    size_t recommended_buffer_size_bytes{1024 * 1024};
    size_t recommended_shm_slot_size{0};
};

struct CalibrationResult {
    GpuInfo gpu;
    ThermalProfile thermal;
    MemoryProfile memory;

    // Derived tuning parameters
    float ewma_alpha{0.2f};
    uint64_t starvation_threshold_ms{250};
    float hysteresis_degrade_temp{80.0f};
    float hysteresis_recover_temp{72.0f};
    uint32_t shm_ring_slot_count{16};

    float calibration_duration_sec{0.0f};
    std::string platform_class{"unknown"}; // "nano", "nx", "orin", "x86_dev"
};

class HardwareProfiler {
public:
    HardwareProfiler() = default;

    /**
     * Run the full calibration suite. Takes ~30-60 seconds.
     */
    CalibrationResult calibrate(bool verbose = true) {
        CalibrationResult result;
        auto start = std::chrono::steady_clock::now();

        if (verbose) std::cout << "[HardwareProfiler] Starting SoC calibration..." << std::endl;

        // Phase 1: GPU Detection
        result.gpu = detect_gpu(verbose);

        // Phase 2: Memory Analysis
        result.memory = analyze_memory(result.gpu, verbose);

        // Phase 3: Thermal Profiling (requires sustained load)
        result.thermal = profile_thermal(verbose);

        // Phase 4: Derive optimal parameters
        derive_tuning_params(result);

        // Phase 5: Classify platform
        result.platform_class = classify_platform(result.gpu);

        auto end = std::chrono::steady_clock::now();
        result.calibration_duration_sec = std::chrono::duration<float>(end - start).count();

        if (verbose) {
            std::cout << "[HardwareProfiler] Calibration complete in "
                      << result.calibration_duration_sec << "s" << std::endl;
            std::cout << "[HardwareProfiler] Platform: " << result.platform_class << std::endl;
        }

        return result;
    }

    /**
     * Export calibration result to YAML configuration file.
     */
    static bool export_yaml(const CalibrationResult& result, const std::string& path) {
        std::ofstream out(path);
        if (!out.is_open()) return false;

        out << "# EdgeModelScheduler Hardware Profile\n";
        out << "# Auto-generated by HardwareProfiler\n";
        out << "# Platform: " << result.platform_class << "\n\n";

        out << "gpu:\n";
        out << "  device_name: \"" << result.gpu.device_name << "\"\n";
        out << "  sm_count: " << result.gpu.sm_count << "\n";
        out << "  cuda_cores: " << result.gpu.cuda_cores << "\n";
        out << "  total_memory_mb: " << (result.gpu.total_memory_bytes / (1024 * 1024)) << "\n";
        out << "  compute_capability: " << result.gpu.compute_major << "." << result.gpu.compute_minor << "\n";
        out << "  peak_bandwidth_gbps: " << result.gpu.peak_bandwidth_gbps << "\n\n";

        out << "thermal:\n";
        out << "  idle_temp_c: " << result.thermal.idle_temp_c << "\n";
        out << "  sustained_temp_c: " << result.thermal.sustained_temp_c << "\n";
        out << "  rise_rate_c_per_sec: " << result.thermal.thermal_rise_rate_c_per_sec << "\n";
        out << "  dissipation_rate_c_per_sec: " << result.thermal.thermal_dissipation_rate_c_per_sec << "\n";
        out << "  throttle_threshold_c: " << result.thermal.recommended_throttle_threshold_c << "\n";
        out << "  recovery_threshold_c: " << result.thermal.recommended_recovery_threshold_c << "\n\n";

        out << "memory:\n";
        out << "  total_system_ram_mb: " << (result.memory.total_system_ram_bytes / (1024 * 1024)) << "\n";
        out << "  pool_capacity: " << result.memory.recommended_pool_capacity << "\n";
        out << "  buffer_size_bytes: " << result.memory.recommended_buffer_size_bytes << "\n";
        out << "  shm_slot_size_bytes: " << result.memory.recommended_shm_slot_size << "\n\n";

        out << "scheduler:\n";
        out << "  ewma_alpha: " << result.ewma_alpha << "\n";
        out << "  starvation_threshold_ms: " << result.starvation_threshold_ms << "\n";
        out << "  hysteresis_degrade_temp_c: " << result.hysteresis_degrade_temp << "\n";
        out << "  hysteresis_recover_temp_c: " << result.hysteresis_recover_temp << "\n";
        out << "  shm_ring_slot_count: " << result.shm_ring_slot_count << "\n\n";

        out << "calibration:\n";
        out << "  duration_sec: " << result.calibration_duration_sec << "\n";
        out << "  platform_class: \"" << result.platform_class << "\"\n";

        out.close();
        return true;
    }

    /**
     * Load calibration from existing YAML (simple key-value parser).
     */
    static CalibrationResult load_yaml(const std::string& path) {
        CalibrationResult result;
        std::ifstream in(path);
        if (!in.is_open()) {
            throw std::runtime_error("Cannot open hardware profile: " + path);
        }

        std::string line;
        while (std::getline(in, line)) {
            // Trim and skip comments/empty
            auto pos = line.find('#');
            if (pos != std::string::npos) line = line.substr(0, pos);
            // Simple key-value extraction
            auto colon = line.find(':');
            if (colon == std::string::npos) continue;

            std::string key = line.substr(0, colon);
            std::string val = line.substr(colon + 1);
            // Trim whitespace
            key.erase(0, key.find_first_not_of(" \t"));
            key.erase(key.find_last_not_of(" \t") + 1);
            val.erase(0, val.find_first_not_of(" \t\""));
            val.erase(val.find_last_not_of(" \t\"") + 1);

            if (val.empty()) continue;

            if (key == "ewma_alpha") result.ewma_alpha = std::stof(val);
            else if (key == "starvation_threshold_ms") result.starvation_threshold_ms = std::stoull(val);
            else if (key == "hysteresis_degrade_temp_c") result.hysteresis_degrade_temp = std::stof(val);
            else if (key == "hysteresis_recover_temp_c") result.hysteresis_recover_temp = std::stof(val);
            else if (key == "shm_ring_slot_count") result.shm_ring_slot_count = std::stoul(val);
            else if (key == "pool_capacity") result.memory.recommended_pool_capacity = std::stoul(val);
            else if (key == "buffer_size_bytes") result.memory.recommended_buffer_size_bytes = std::stoull(val);
            else if (key == "platform_class") result.platform_class = val;
            else if (key == "device_name") result.gpu.device_name = val;
            else if (key == "sm_count") result.gpu.sm_count = std::stoul(val);
        }

        return result;
    }

private:
    GpuInfo detect_gpu(bool verbose) {
        GpuInfo info;

#ifdef HAS_CUDA
        int device_count = 0;
        cudaGetDeviceCount(&device_count);
        if (device_count > 0) {
            cudaDeviceProp prop;
            cudaGetDeviceProperties(&prop, 0);
            info.device_name = prop.name;
            info.sm_count = prop.multiProcessorCount;
            info.compute_major = prop.major;
            info.compute_minor = prop.minor;
            info.max_threads_per_sm = prop.maxThreadsPerMultiProcessor;
            info.total_memory_bytes = prop.totalGlobalMem;

            // Approximate CUDA cores per SM based on compute capability
            int cores_per_sm = 128; // Default (Ampere/Ada)
            if (prop.major == 7) cores_per_sm = 64;       // Volta/Turing
            else if (prop.major == 8) cores_per_sm = 128;  // Ampere
            else if (prop.major == 9) cores_per_sm = 128;  // Hopper
            info.cuda_cores = info.sm_count * cores_per_sm;

            // Memory bandwidth (approximate from clock * bus width)
            float bw = (prop.memoryClockRate * 1e3f) * (prop.memoryBusWidth / 8.0f) * 2.0f;
            info.peak_bandwidth_gbps = bw / 1e9f;

            size_t free_mem = 0, total_mem = 0;
            cudaMemGetInfo(&free_mem, &total_mem);
            info.free_memory_bytes = free_mem;
        }
#endif

        if (verbose) {
            std::cout << "[HardwareProfiler] GPU: " << info.device_name
                      << " (" << info.sm_count << " SMs, "
                      << info.cuda_cores << " cores)" << std::endl;
        }
        return info;
    }

    MemoryProfile analyze_memory(const GpuInfo& gpu, bool verbose) {
        MemoryProfile mem;

        // Read system RAM from /proc/meminfo (Linux)
        std::ifstream meminfo("/proc/meminfo");
        if (meminfo.is_open()) {
            std::string line;
            while (std::getline(meminfo, line)) {
                if (line.find("MemTotal:") == 0) {
                    uint64_t kb = 0;
                    std::sscanf(line.c_str(), "MemTotal: %lu kB", &kb);
                    mem.total_system_ram_bytes = kb * 1024;
                } else if (line.find("MemAvailable:") == 0) {
                    uint64_t kb = 0;
                    std::sscanf(line.c_str(), "MemAvailable: %lu kB", &kb);
                    mem.available_ram_bytes = kb * 1024;
                }
            }
        }

        // Scale pool capacity based on available memory
        if (mem.total_system_ram_bytes > 16ULL * 1024 * 1024 * 1024) {
            // 16GB+ (Orin AGX)
            mem.recommended_pool_capacity = 16;
            mem.recommended_buffer_size_bytes = 4 * 1024 * 1024; // 4MB
        } else if (mem.total_system_ram_bytes > 8ULL * 1024 * 1024 * 1024) {
            // 8GB (Orin NX)
            mem.recommended_pool_capacity = 8;
            mem.recommended_buffer_size_bytes = 2 * 1024 * 1024; // 2MB
        } else {
            // 4GB or less (Nano)
            mem.recommended_pool_capacity = 4;
            mem.recommended_buffer_size_bytes = 1024 * 1024; // 1MB
        }

        // SHM slot size: 1080p RGB frame
        mem.recommended_shm_slot_size = 1920 * 1080 * 3;

        if (verbose) {
            std::cout << "[HardwareProfiler] RAM: "
                      << (mem.total_system_ram_bytes / (1024 * 1024)) << "MB total, "
                      << (mem.available_ram_bytes / (1024 * 1024)) << "MB available"
                      << std::endl;
        }
        return mem;
    }

    ThermalProfile profile_thermal(bool verbose) {
        ThermalProfile tp;

        // Read baseline idle temperature
        tp.idle_temp_c = read_current_temp();

        if (verbose) {
            std::cout << "[HardwareProfiler] Idle temp: " << tp.idle_temp_c << "°C" << std::endl;
            std::cout << "[HardwareProfiler] Running thermal stress test (5s)..." << std::endl;
        }

        // Brief stress to measure rise rate
        float temp_before = tp.idle_temp_c;
        auto stress_start = std::chrono::steady_clock::now();

        // Spin all CPU cores for 5 seconds to generate heat
        std::atomic<bool> stress_active{true};
        std::vector<std::thread> stress_threads;
        unsigned int hw_threads = std::thread::hardware_concurrency();
        if (hw_threads == 0) hw_threads = 4;

        for (unsigned int i = 0; i < hw_threads; ++i) {
            stress_threads.emplace_back([&stress_active]() {
                volatile double x = 1.0;
                while (stress_active.load(std::memory_order_relaxed)) {
                    x = x * 1.00001 + 0.00001; // CPU-bound spin
                }
            });
        }

        std::this_thread::sleep_for(std::chrono::seconds(5));
        stress_active = false;
        for (auto& t : stress_threads) t.join();

        float temp_after = read_current_temp();
        auto stress_end = std::chrono::steady_clock::now();
        float stress_duration = std::chrono::duration<float>(stress_end - stress_start).count();

        tp.sustained_temp_c = temp_after;
        tp.thermal_rise_rate_c_per_sec = (temp_after - temp_before) / stress_duration;

        // Wait 5s and measure cooling rate
        if (verbose) {
            std::cout << "[HardwareProfiler] Post-stress temp: " << temp_after
                      << "°C. Measuring cooling rate (5s)..." << std::endl;
        }

        std::this_thread::sleep_for(std::chrono::seconds(5));
        float temp_cooled = read_current_temp();
        tp.thermal_dissipation_rate_c_per_sec = (temp_after - temp_cooled) / 5.0f;

        // Derive thresholds
        // Throttle at 85% of thermal headroom from idle to Tj_max (assumed 105°C)
        float tj_max = 105.0f;
        tp.recommended_throttle_threshold_c = tp.idle_temp_c + (tj_max - tp.idle_temp_c) * 0.75f;
        // Recover 8°C below throttle (hysteresis)
        tp.recommended_recovery_threshold_c = tp.recommended_throttle_threshold_c - 8.0f;

        if (verbose) {
            std::cout << "[HardwareProfiler] Thermal rise: " << tp.thermal_rise_rate_c_per_sec
                      << "°C/s, dissipation: " << tp.thermal_dissipation_rate_c_per_sec
                      << "°C/s" << std::endl;
            std::cout << "[HardwareProfiler] Recommended thresholds: throttle="
                      << tp.recommended_throttle_threshold_c << "°C, recover="
                      << tp.recommended_recovery_threshold_c << "°C" << std::endl;
        }

        return tp;
    }

    void derive_tuning_params(CalibrationResult& result) {
        // EWMA alpha: slower smoothing for high-latency platforms
        if (result.gpu.sm_count >= 64) {
            result.ewma_alpha = 0.15f; // High-end: smoother
        } else if (result.gpu.sm_count >= 16) {
            result.ewma_alpha = 0.2f;  // Mid-range
        } else {
            result.ewma_alpha = 0.3f;  // Low-end: react faster
        }

        // Starvation threshold: proportional to available compute
        result.starvation_threshold_ms = (result.gpu.sm_count >= 32) ? 500 : 250;

        // Hysteresis from thermal profile
        result.hysteresis_degrade_temp = result.thermal.recommended_throttle_threshold_c;
        result.hysteresis_recover_temp = result.thermal.recommended_recovery_threshold_c;

        // SHM ring slots: more for high-memory platforms
        result.shm_ring_slot_count = (result.memory.total_system_ram_bytes > 8ULL * 1024 * 1024 * 1024) ? 32 : 16;
    }

    std::string classify_platform(const GpuInfo& gpu) {
        if (gpu.device_name.find("Orin") != std::string::npos) {
            if (gpu.sm_count >= 16) return "orin_agx";
            if (gpu.sm_count >= 8) return "orin_nx";
            return "orin_nano";
        }
        if (gpu.device_name.find("Xavier") != std::string::npos) return "xavier";
        if (gpu.device_name.find("Nano") != std::string::npos) return "nano";
        if (gpu.sm_count == 0) return "cpu_only";
        return "x86_dev";
    }

    float read_current_temp() {
        std::ifstream temp_file("/sys/devices/virtual/thermal/thermal_zone0/temp");
        if (temp_file.is_open()) {
            long temp;
            temp_file >> temp;
            return static_cast<float>(temp) / 1000.0f;
        }
        return 45.0f; // Mock for non-Linux dev machines
    }
};

} // namespace edge_scheduler
